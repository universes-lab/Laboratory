"""Латчер: кольцо проходит касп своего тора по касательной к его оси (z). Ось полёта — y (от центра тора к центру кольца).
Поворот кольца относительно тора вокруг оси полёта на угол α: входит ли кольцо в тело тора у каспа?
Тело рогатого тора a = b = 1/2: (ρ − ½)² + z² < ¼. Считаем наибольшую «глубину» захода точек кольца в тело.
Запуск: python3 cusp_tilt.py"""
import numpy as np
t = np.linspace(-0.6, 0.6, 200001)                      # участок кольца у каспа (параметр — угол от каспа)
def inside_depth(alpha):
    # кольцо радиуса 1 с центром (0, 1, 0) в плоскости yz, касательная в 0 — вдоль z; затем поворот вокруг оси y на α
    P = np.stack([0*t, 1 - np.cos(t), np.sin(t)], 1)
    c, s = np.cos(alpha), np.sin(alpha); Ry = np.array([[c, 0, s], [0, 1, 0], [-s, 0, c]])
    P = P @ Ry.T
    rho = np.hypot(P[:, 0], P[:, 1]); f = 0.25 - ((rho - 0.5)**2 + P[:, 2]**2)
    return f.max(), (f > 1e-12).sum()
for a in (0, 1e-3, 0.01, 0.05, 0.2):
    d, n = inside_depth(a); print(f"α = {a:6.3f} рад: max(¼ − (ρ−½)² − z²) = {d:+.2e}; точек внутри тела: {n}")
