"""Правило 4 (Интегратор, 26.10): обмен элементами Q1 ↔ Qf. Модель причала (mooring_step.py):
Q1 — касп в 0, ось z, средняя окружность T1 радиуса 1/2; латчер — кольцо r2 (окружность радиуса 1 в плоскости yz, центр (0, 1, 0)),
проходит касп Q1 и касп своего тора T2 (центр (0, 2, 0), ось z). Средние окружности ориентированы по спину тора (+z или −z).
Считаем:
 (1) числа зацепления r2 с T1 и T2 до обмена;
 (2) обмен торами с переносом собственного спина (тор переносится параллельно в позицию партнёра) — числа после;
 (3) J5 на контакте торов (касание в (0, 1, 0)): скорости поверхностей при одинаковом и противоположном спине;
 (4) Qs: кольцо Q1 на экваторе своего тора — направление его хода против хода поверхности тора после обмена.
Запуск: python3 rule4_swap.py"""
import numpy as np
def circle(c, e1, e2, r, n=3000):
    t = np.linspace(0, 2*np.pi, n, endpoint=False); return c + r*(np.outer(np.cos(t), e1) + np.outer(np.sin(t), e2))
def Lk(P, Q):
    dP = np.roll(P, -1, 0) - P; dQ = np.roll(Q, -1, 0) - Q; mP = P + dP/2; mQ = Q + dQ/2
    R = mP[:, None] - mQ[None]; num = np.einsum('ijk,ijk->ij', R, np.cross(dP[:, None], dQ[None]))
    return (num / np.linalg.norm(R, axis=2)**3).sum() / (4*np.pi)
X, Y, Z = np.eye(3)
r2 = circle(np.array([0, 1.0, 0]), -Y, Z, 1.0, 2000)          # (0, 1 − cos t, sin t): в 0 идёт вверх (+z), в (0, 2, 0) — вниз
def core(c, s):  # s = +1: спин +z (против часовой, если смотреть с +z)
    return circle(np.asarray(c, float), X, s*Y, 0.5, 1500)
P1, P2 = np.zeros(3), np.array([0, 2.0, 0])
print("контакт торов: расстояние средних окружностей =",
      round(np.min(np.linalg.norm(core(P1, 1)[:, None] - core(P2, 1)[None], axis=2)), 4), "(касание — 1)")
for s1, s2 in ((1, 1), (1, -1)):
    a, b = Lk(r2, core(P1, s1)), Lk(r2, core(P2, s2))
    a2, b2 = Lk(r2, core(P1, s2)), Lk(r2, core(P2, s1))           # после обмена: в P1 тор со спином s2, в P2 — со спином s1
    pt = np.array([0, 1.0, 0])
    v1 = np.cross(s1*Z, pt - P1); v2 = np.cross(s2*Z, pt - P2)   # скорости поверхностей в точке касания
    print(f"спины T1 = {s1:+d}z, T2 = {s2:+d}z: до обмена Lk(r2,T1) = {a:+.3f}, Lk(r2,T2) = {b:+.3f}; "
          f"после обмена Lk(r2, в P1) = {a2:+.3f}, Lk(r2, в P2) = {b2:+.3f}; "
          f"J5 в точке касания: v1 = {v1}, v2 = {v2} → {'проскальзывание (J5 нарушено)' if np.dot(v1, v2) < 0 else 'непрерывность (J5)'}")
print("Qs: кольцо Q1 на внешнем экваторе (радиус 1), ход кольца совпадает с ходом тора T1 (+z) до обмена;")
pt = np.array([1.0, 0, 0]); ring_v = np.cross(Z, pt); torus_after = np.cross(-Z, pt)
print(f"   после обмена тор в P1 со спином −z: ход кольца {ring_v}, ход поверхности тора {torus_after} → "
      f"{'встречно на линии касания' if np.dot(ring_v, torus_after) < 0 else 'вместе'}")
